    local lang="$1"
    
    case "$lang" in
        nodejs)
            echo "### Node.js Dependencies"
            echo "- Updated npm packages to latest versions"
            echo "- Installed security patches"
            ;;
        python)
            echo "### Python Dependencies"
            echo "- Updated pip requirements to latest versions"
            echo "- Security vulnerabilities addressed"
            ;;
        docker)
            echo "### Docker Base Images"
            echo "- Updated base images to latest tags"
            echo "- Applied security patches"
            ;;
        java)
            echo "### Java Dependencies"
            echo "- Updated Maven/Gradle dependencies"
            echo "- Applied security updates"
            ;;
        go)
            echo "### Go Dependencies"
            echo "- Updated Go modules"
            echo "- Applied latest patches"
            ;;
        rust)
            echo "### Rust Dependencies"
            echo "- Updated Cargo crates"
            echo "- Applied security patches"
            ;;
    esac
}

generate_commit_metadata() {
    local log_func="${1:-echo}"
    
    {
        echo "Automated Dependency Update"
        echo ""
        echo "Updated Dependencies:"
        for lang in "${UPDATED_LANGUAGES[@]}"; do
            echo "  - $lang: $DEPENDENCIES_UPDATED new packages"
        done
        echo ""
        echo "Security Audit: $([ "$SECURITY_UPDATES" == "true" ] && echo "PASS with updates" || echo "PASS")"
        echo "Breaking Changes: $([ "$BREAKING_CHANGES" == "true" ] && echo "YES" || echo "NO")"
        echo "Timestamp: $(date)"
        echo ""
        echo "Generated by: Dependency Updater v1.0"
    }
}
