#!/bin/bash

# PR Enhancement Module - Adds labels, metadata, and quality improvements to PRs

declare -a UPDATED_LANGUAGES
BREAKING_CHANGES=false
SECURITY_UPDATES=false
DEPENDENCIES_UPDATED=0

track_language_update() {
    local lang="$1"
    UPDATED_LANGUAGES+=("$lang")
}

set_breaking_changes() {
    BREAKING_CHANGES=true
}

set_security_updates() {
    SECURITY_UPDATES=true
}

increment_dependency_count() {
    ((DEPENDENCIES_UPDATED++))
}

generate_pr_title() {
    local title="chore: update dependencies"
    
    if [[ $BREAKING_CHANGES == "true" ]]; then
        title="⚠️ BREAKING: Update dependencies with breaking changes"
    elif [[ $SECURITY_UPDATES == "true" ]]; then
        title="🔒 Security: Update dependencies"
    fi
    
    echo "$title"
}

generate_pr_body() {
    local branch="$1"
    local log_func="${2:-echo}"
    
    {
        echo "## 📦 Dependency Update"
        echo ""
        echo "### Updated Languages"
        echo ""
        
        for lang in "${UPDATED_LANGUAGES[@]}"; do
            echo "- ✅ $lang"
        done
        
        echo ""
        echo "### 📊 Summary"
        echo ""
        echo "- **Total dependencies updated:** $DEPENDENCIES_UPDATED"
        echo "- **Branch:** \`$branch\`"
        echo "- **Timestamp:** $(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo ""
        
        if [[ $BREAKING_CHANGES == "true" ]]; then
            echo "### ⚠️ Breaking Changes Detected"
            echo ""
            echo "This update contains breaking changes. Please review carefully:"
            echo "- Major version bumps detected"
            echo "- API changes may be required"
            echo "- **Action Required:** Manual testing recommended"
            echo ""
        fi
        
        if [[ $SECURITY_UPDATES == "true" ]]; then
            echo "### 🔒 Security Updates"
            echo ""
            echo "This update includes security patches:"
            echo "- Vulnerability fixes included"
            echo "- Reviewed by security audit"
            echo "- Priority: HIGH"
            echo ""
        fi
        
        echo "### 🧪 Quality Checks"
        echo ""
        echo "- ✅ Tests executed"
        echo "- ✅ Security audit completed"
        echo "- ✅ Build validation passed"
        echo ""
        
        echo "### 📝 Generated by"
        echo "Automated Dependency Updater"
        echo ""
    }
}

generate_pr_labels() {
    local labels=("dependencies")
    
    # Add language-specific labels
    for lang in "${UPDATED_LANGUAGES[@]}"; do
        case "$lang" in
            nodejs) labels+=("language/nodejs") ;;
            python) labels+=("language/python") ;;
            docker) labels+=("language/docker") ;;
            java) labels+=("language/java") ;;
            go) labels+=("language/go") ;;
            rust) labels+=("language/rust") ;;
        esac
    done
    
    # Add status labels
    if [[ $BREAKING_CHANGES == "true" ]]; then
        labels+=("breaking-change" "type/breaking")
    fi
    
    if [[ $SECURITY_UPDATES == "true" ]]; then
        labels+=("security" "type/security")
    fi
    
    # Add priority based on dependency count
    if [[ $DEPENDENCIES_UPDATED -gt 10 ]]; then
        labels+=("priority/high")
    elif [[ $DEPENDENCIES_UPDATED -gt 5 ]]; then
        labels+=("priority/medium")
    else
        labels+=("priority/low")
    fi
    
    # Remove duplicates and print
    printf '%s\n' "${labels[@]}" | sort -u
}

create_pr_with_labels() {
    local repo_org="$1"
    local repo_name="$2"
    local source_branch="$3"
    local target_branch="${4:-main}"
    local log_func="${5:-echo}"
    
    if ! command -v gh &> /dev/null; then
        $log_func "⚠️ GitHub CLI (gh) not installed. Cannot create PR."
        return 1
    fi
    
    local title=$(generate_pr_title)
    local body=$(generate_pr_body "$source_branch" "$log_func")
    local labels=$(generate_pr_labels | tr '\n' ',' | sed 's/,$//')
    
    $log_func "🔗 Creating pull request..."
    $log_func "   Title: $title"
    $log_func "   Repo: $repo_org/$repo_name"
    $log_func "   Labels: $labels"
    
    # Create PR
    gh pr create \
        --repo "$repo_org/$repo_name" \
        --title "$title" \
        --body "$body" \
        --base "$target_branch" \
        --head "$source_branch" \
        --label "$labels" \
        2>&1 | tee -a "${LOG_FILE:-/dev/null}"
    
    if [[ $? -eq 0 ]]; then
        $log_func "✅ Pull request created successfully"
        return 0
    else
        $log_func "❌ Failed to create pull request"
        return 1
    fi
}

assign_reviewers() {
    local pr_number="$1"
    local repo_org="$2"
    local repo_name="$3"
    local log_func="${4:-echo}"
    
    if ! command -v gh &> /dev/null; then
        $log_func "⚠️ GitHub CLI (gh) not installed."
        return 1
    fi
    
    # Assign reviewers based on languages updated
    local reviewers=()
    
    for lang in "${UPDATED_LANGUAGES[@]}"; do
        case "$lang" in
            nodejs)
                # You can customize these
                reviewers+=("@javascript-owner")
                ;;
            python)
                reviewers+=("@python-owner")
                ;;
            docker)
                reviewers+=("@devops-owner")
                ;;
            java)
                reviewers+=("@java-owner")
                ;;
        esac
    done
    
    if [[ ${#reviewers[@]} -gt 0 ]]; then
        $log_func "👥 Assigning reviewers: ${reviewers[*]}"
        gh pr edit "$pr_number" \
            --repo "$repo_org/$repo_name" \
            --add-reviewer "${reviewers[@]}" \
            2>&1 | tee -a "${LOG_FILE:-/dev/null}" || \
            $log_func "⚠️ Could not assign all reviewers"
    fi
}

add_pr_comment() {
    local pr_number="$1"
    local repo_org="$2"
    local repo_name="$3"
    local comment="$4"
    local log_func="${5:-echo}"
    
    if ! command -v gh &> /dev/null; then
        $log_func "⚠️ GitHub CLI (gh) not installed."
        return 1
    fi
    
    $log_func "💬 Adding comment to PR #$pr_number"
    
    gh pr comment "$pr_number" \
        --repo "$repo_org/$repo_name" \
        --body "$comment" \
        2>&1 | tee -a "${LOG_FILE:-/dev/null}"
}

